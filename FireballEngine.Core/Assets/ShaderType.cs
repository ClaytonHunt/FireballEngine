namespace FireballEngine.Core.Assets;

/// <summary>
/// Represents the different types of shaders available in the Fireball Engine.
/// </summary>
public enum ShaderType
{
    /// <summary>
    /// A basic color shader.
    /// </summary>
    BasicColor,

    /// <summary>
    /// A shader used for rendering sprites.
    /// </summary>
    Sprite,

    /// <summary>
    /// A shader that supports lighting effects.
    /// </summary>
    Lit
}
